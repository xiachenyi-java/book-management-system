/*
💍 用"结婚誓词"理解事务
你原来的"病"：结到一半说"算了"
delete 方法里有两件事：
删除图书（把书从书架抽走）
重排序号（把剩下的书重新贴标签 1,2,3...）
以前的问题：书抽走了（第 1 步成功），贴标签贴到一半数据库断了（第 2 步失败）。结果书没了，标签还是乱的（1,2,4,5,6）。
就像结婚：戒指戴了一半，司仪问"你愿意吗"，你说"算了"。这算结了还是没结？ 数据就卡在这种"半吊子"状态。
事务的解决办法：要么全做，要么全不做
java
@Transactional
public void delete(Integer id) {
    // 1. 删书
    // 2. 重排
    // 如果中间任何一步报错，Spring 会自动"撤销"所有操作
}
@Transactional 就像结婚誓词："无论好坏，要么一起过，要么不过。"不存在"删了书但序号没排好"的中间状态。
🏗️ 事务的 ACID（先记一个 A）
表格
字母	英文	中文	含义
A	Atomicity	原子性	操作不可分割，要么全成功，要么全失败
C	Consistency	一致性	数据始终保持合法状态（先不深入）
I	Isolation	隔离性	多个事务互不干扰（先不深入）
D	Durability	持久性	成功后就永久保存（先不深入）
你现在只需要理解 A：delete 方法里的"删书 + 重排"是一个原子操作，不能拆开。
 */