/*
用"医院挂号建档"的比喻来理解整个流程：
一、注册接口是做什么的？
简单说：前端把用户的账号密码交过来，后端检查没问题后，存进数据库，返回"注册成功"。
就像去医院首次挂号建档：
你填一张登记表（账号、密码）
前台检查你有没有重复挂号（用户名是否已存在）
医院把你的信息存档（存入数据库）
给你一张就诊卡（返回注册成功 + 用户信息）
你可能想问：直接一个方法把参数接进来、查库、保存不就行了吗？为什么要分 DTO、Service、Result？
表格
如果不这样做	会出现什么问题
直接用 User 实体接参数	前端可能传进 id、isAdmin 等危险字段，被恶意利用
不写 @Valid	数据库里出现空用户名、超短密码等脏数据
Controller 直接操作数据库	代码臃肿，登录、修改密码都要重写一遍查库逻辑
返回格式不统一	前端要处理 10 种不同的返回结构，崩溃
不写 API 文档	前后端联调靠吼，改个字段要翻源码
用户注册接口 = 前台（Controller）收表格 → 检查（@Valid）→ 转交后台（Service）办理 → 密码加密 → 存档 → 统一信封（Result）返还。
DTO 保证安全，Service 保证复用，Result 保证规范，三者配合就是一个企业级接口的标准姿势。
 */